import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_SEASON = "2026-27";
const WIZARDS_TEAM_ID = "1610612764";
const WINDOW_HOURS_AFTER_TIP = 4;

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function isValidSeason(value) {
  return /^\d{4}-\d{2}$/.test(String(value || "").trim());
}

function isWizardsGame(game) {
  const teamIds = [
    game?.homeTeam?.teamId,
    game?.awayTeam?.teamId,
  ].map((value) => String(value || "").trim());
  return teamIds.includes(WIZARDS_TEAM_ID);
}

function sqlString(value) {
  return `'${String(value ?? "").replaceAll("'", "''")}'`;
}

function formatIso(date) {
  return date.toISOString();
}

function hourSpec(startHour, endHour) {
  if (startHour === endHour) return String(startHour);
  return `${startHour}-${endHour}`;
}

function dateKeyUtc(date) {
  return `${date.getUTCFullYear()}-${String(date.getUTCMonth() + 1).padStart(2, "0")}-${String(date.getUTCDate()).padStart(2, "0")}`;
}

function buildCronSegments(start, end) {
  const segments = [];
  let cursor = new Date(Date.UTC(start.getUTCFullYear(), start.getUTCMonth(), start.getUTCDate()));
  const endDateKey = dateKeyUtc(end);

  while (dateKeyUtc(cursor) <= endDateKey) {
    const sameStartDate = dateKeyUtc(cursor) === dateKeyUtc(start);
    const sameEndDate = dateKeyUtc(cursor) === endDateKey;
    const startHour = sameStartDate ? start.getUTCHours() : 0;
    const endHour = sameEndDate ? end.getUTCHours() : 23;
    segments.push({
      cron: `*/5 ${hourSpec(startHour, endHour)} ${cursor.getUTCDate()} ${cursor.getUTCMonth() + 1} *`,
    });
    cursor = new Date(cursor.getTime() + (24 * 60 * 60 * 1000));
  }

  return segments;
}

function compareGames(left, right) {
  return String(left.gameTimeUTC || "").localeCompare(String(right.gameTimeUTC || ""))
    || String(left.gameId || "").localeCompare(String(right.gameId || ""));
}

function buildCommand(gameId, windowStartIso, windowEndIso) {
  return `
    select net.http_post(
      url := (
        select decrypted_secret from vault.decrypted_secrets
        where name = 'nba_dash_project_url'
        limit 1
      ) || '/functions/v1/wizards-analysis-prewarm',
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'apikey', (
          select decrypted_secret from vault.decrypted_secrets
          where name = 'nba_dash_service_role_key'
          limit 1
        ),
        'Authorization', 'Bearer ' || (
          select decrypted_secret from vault.decrypted_secrets
          where name = 'nba_dash_service_role_key'
          limit 1
        )
      ),
      body := jsonb_build_object(
        'source', 'pg_cron',
        'schedule', 'wizards-game-window',
        'gameIds', jsonb_build_array('${gameId}')
      )
    )
    where now() >= ${sqlString(windowStartIso)}::timestamptz
      and now() <= ${sqlString(windowEndIso)}::timestamptz;
  `.trim();
}

function buildSql({ season, generatedAt, jobs, gameCount }) {
  const valueRows = jobs.map((job) => [
    sqlString(job.jobName),
    sqlString(job.cron),
    sqlString(job.command),
  ].join(", ")).map((row) => `    (${row})`);

  return `-- Schedules Wizards-only shared Analysis prewarmer jobs.
-- Generated by scripts/update-wizards-analysis-prewarm-schedule.mjs.
-- Source schedule season: ${season}
-- Generated at: ${generatedAt}
-- Wizards games scheduled: ${gameCount}
-- Cron jobs scheduled: ${jobs.length}
--
-- Each job only calls the Edge Function during its exact game window:
-- scheduled tip through ${WINDOW_HOURS_AFTER_TIP} hours after tip.
--
-- Prerequisites:
-- 1. Deploy the wizards-analysis-prewarm Edge Function.
-- 2. Store these secrets in Supabase Vault:
--    - nba_dash_project_url: https://<project-ref>.supabase.co
--    - nba_dash_service_role_key: <service role key>

create extension if not exists pg_cron with schema extensions;
create extension if not exists pg_net with schema extensions;

do $$
declare
  existing_job record;
begin
  for existing_job in
    select jobid
    from cron.job
    where jobname = 'wizards-analysis-prewarm'
       or jobname like 'wizards-analysis-prewarm-%'
  loop
    perform cron.unschedule(existing_job.jobid);
  end loop;
end
$$;

with jobs(job_name, cron_schedule, command_sql) as (
  values
${valueRows.join(",\n")}
)
select cron.schedule(job_name, cron_schedule, command_sql)
from jobs
order by job_name;
`;
}

async function main() {
  const season = String(process.argv[2] || DEFAULT_SEASON).trim();
  if (!isValidSeason(season)) {
    throw new Error("Usage: node scripts/update-wizards-analysis-prewarm-schedule.mjs 2026-27");
  }

  const seasonToken = season.replace("-", "_");
  const schedulePath = path.join(repoRoot, "src", "data", `nbaSchedule${seasonToken}.json`);
  const schedulePayload = JSON.parse(await fs.readFile(schedulePath, "utf8"));
  const games = (Array.isArray(schedulePayload?.games) ? schedulePayload.games : [])
    .filter(isWizardsGame)
    .filter((game) => String(game?.gameTimeUTC || "").trim())
    .sort(compareGames);

  const jobs = [];
  for (const game of games) {
    const windowStart = new Date(String(game.gameTimeUTC));
    if (Number.isNaN(windowStart.getTime())) continue;
    const windowEnd = new Date(windowStart.getTime() + (WINDOW_HOURS_AFTER_TIP * 60 * 60 * 1000));
    const windowStartIso = formatIso(windowStart);
    const windowEndIso = formatIso(windowEnd);
    buildCronSegments(windowStart, windowEnd).forEach((segment, segmentIndex) => {
      jobs.push({
        jobName: `wizards-analysis-prewarm-${game.gameId}-${segmentIndex + 1}`,
        cron: segment.cron,
        command: buildCommand(game.gameId, windowStartIso, windowEndIso),
      });
    });
  }

  if (!jobs.length) {
    throw new Error(`No Wizards games with valid tip times found in ${schedulePath}.`);
  }

  const sql = buildSql({
    season,
    generatedAt: new Date().toISOString(),
    jobs,
    gameCount: games.length,
  });
  const outputPath = path.join(repoRoot, "supabase", "wizards_analysis_prewarm_schedule.sql");
  await fs.writeFile(outputPath, sql);
  console.log(`Wrote ${jobs.length} cron jobs for ${games.length} Wizards games to ${outputPath}.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
